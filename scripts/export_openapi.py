"""Exports each service's OpenAPI spec to docs/openapi/*.json and regenerates the endpoint index
in docs/API_REFERENCE.md (between the ENDPOINT-INDEX markers).

    python scripts/export_openapi.py
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "common")]
os.environ.setdefault("BQ_ENABLED", "false")   # specs only; no connections are opened

SERVICES = [
    ("integration-layer", "integration_layer.main", "Integration Layer", 8000),
    ("consumer-application", "consumer_application.main", "ConsumerApplication", 8001),
    ("wwmg-source", "wwmg_source.main", "WWMG_Source", 8002),
    ("mycarehub", "mycarehub.main", "MyCareHub", 8003),
    ("console", "console.main", "Console backend", 8080),
]


def main() -> None:
    out_dir = ROOT / "docs" / "openapi"
    out_dir.mkdir(parents=True, exist_ok=True)
    index = ["<!-- ENDPOINT-INDEX:START (generated by scripts/export_openapi.py) -->", ""]
    for slug, module, title, port in SERVICES:
        app = __import__(module, fromlist=["app"]).app
        spec = app.openapi()
        (out_dir / f"{slug}.json").write_text(json.dumps(spec, indent=2))
        index += [f"### {title} (port {port})", "", f"OpenAPI: `docs/openapi/{slug}.json` · Swagger UI: `http://localhost:{port}/docs`", "",
                  "| Method | Path | Summary |", "|---|---|---|"]
        for path, ops in spec["paths"].items():
            for method, op in ops.items():
                summary = (op.get("summary") or "").replace("|", "/")
                desc = (op.get("description") or "").split("\n")[0].replace("|", "/")
                index.append(f"| {method.upper()} | `{path}` | {summary}{' — ' + desc if desc else ''} |")
        index.append("")
        print(f"{slug}: {sum(len(v) for v in spec['paths'].values())} operations")
    index.append("<!-- ENDPOINT-INDEX:END -->")
    ref = ROOT / "docs" / "API_REFERENCE.md"
    text = ref.read_text()
    start, end = text.index("<!-- ENDPOINT-INDEX:START"), text.index("<!-- ENDPOINT-INDEX:END -->") + len("<!-- ENDPOINT-INDEX:END -->")
    ref.write_text(text[:start] + "\n".join(index) + text[end:])


if __name__ == "__main__":
    main()
